def main() -> None:
    ROOT.mkdir(parents=True, exist_ok=True)
    authors = []
    books = []
    for author in AUTHORS:
        payload = dict(author)
        author_books = payload.pop("books")
        authors.append(payload)
        books.extend(author_books)
    for book in books:
        if book["id"] == "acemoglu-1":
            book["also"] = ["robinson"]
    (ROOT / "zones.json").write_text(json.dumps(ZONES, ensure_ascii=False, indent=2), encoding="utf-8")
    (ROOT / "authors.json").write_text(json.dumps(authors, ensure_ascii=False, indent=2), encoding="utf-8")
    (ROOT / "books.json").write_text(json.dumps(books, ensure_ascii=False, indent=2), encoding="utf-8")
    ids = [item["id"] for item in authors]
    if len(ids) != len(set(ids)):
        raise SystemExit("duplicate author id")
    book_ids = [item["id"] for item in books]
    if len(book_ids) != len(set(book_ids)):
        raise SystemExit("duplicate book id")
    print(f"zones={len(ZONES)} authors={len(authors)} books={len(books)}")


if __name__ == "__main__":
    main()
